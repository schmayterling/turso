    /// Whether the tag ends with the number of rows the statement processed,
    /// as in `UPDATE 3`.
    pub fn has_row_count(self) -> bool {
        matches!(
            self,
            Self::Copy
                | Self::Delete
                | Self::Fetch
                | Self::Insert
                | Self::Merge
                | Self::Move
                | Self::Select
                | Self::Update
        )
    }

